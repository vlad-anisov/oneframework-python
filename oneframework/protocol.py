"""Что обязаны знать одинаково **все** языки.

Библиотека на Kotlin и библиотека на JavaScript порождают те же документы, что
и питоновская: тот же документ модели, тот же документ вида, тот же отпечаток.
Значит где-то должно лежать знание, из которого эти документы собираются, --
какая у типа колонка, какой виджет по умолчанию, какие поля модель получает
даром.

Три копии одного правила расходятся тихо: не сразу, а на одиннадцатом типе
поля, который добавили в питон и забыли в Kotlin, -- и приложение соберётся,
просто с другим отпечатком вида, а обмен сочтёт два одинаковых приложения
разными.

Поэтому знание одно и лежит **данными**: ``protocol/field-types.json``. Читают
его все три привязки, и никто не порождает: порождай одна -- завести тип поля
можно было бы только её правкой. Состав сторожит ``tests/test_protocol.py``.
"""

from __future__ import annotations

import json
from pathlib import Path

__all__ = ["system_fields", "table_name", "TABLE_PATH", "SOURCE_PATH", "load"]

#: Копия таблицы **внутри пакета**, а не файл над ним.
#:
#: Читается она при ввозе: классы полей берут из неё колонку, виджет и
#: умолчания. Значит она обязана ехать всюду, куда едет пакет, -- а
#: `protocol/` в дереве фреймворка лежит рядом с пакетом, и после установки
#: колесом или после раскола репозиториев его там нет. Ровно так пакет и
#: перестал ввозиться: `pip install` давал `FileNotFoundError` на первом же
#: `import oneframework`, и заметить это в монорепозитории было нечем.
#:
#: Так же поступают и соседи: у JavaScript копия лежит в корне библиотеки, у
#: Kotlin таблица вкомпилирована в `FieldTypes.kt`. Совпадение копий с
#: образцом сторожит `tests/test_three_languages.py`.
TABLE_PATH = Path(__file__).resolve().parent / "field-types.json"

#: Образец, из которого копия берётся. В установленном пакете его нет -- он
#: нужен только сторожу и тому, кто правит таблицу.
SOURCE_PATH = Path(__file__).resolve().parents[1] / "protocol" / "field-types.json"

#: Версия договора. Растёт, когда меняется **форма** таблицы, а не её
#: содержимое: новый тип поля версию не двигает, новый ключ у типа -- двигает.
VERSION = 1

#: Поля, которые модель получает даром, в том порядке, в каком их заводит
#: :class:`~oneframework.model.meta.ModelMeta`. Порядок здесь -- не оформление:
#: документ модели печатает поля по нему, а отпечаток считается от документа.
SYSTEM_FIELD_ORDER = ("id", "hlc", "created_at", "updated_at")

#: Имя связанной модели у пробного поля. Ссылочному полю без неё не создаться,
#: а в договоре ей делать нечего -- по этой метке она оттуда и вычищается.
_ПРОБА = "__проба__"


def system_fields():
    """Документы четырёх даровых полей -- ровно те, что печатает питон.

    Отдаются документом, а не описанием, потому что другому языку нужен именно
    документ: он его допишет к объявленным полям и получит тот же отпечаток.
    """
    from .model.meta import Model
    from .model.schema import field_schema

    class _Проба(Model):
        pass

    return {name: field_schema(_Проба._fields[name]) for name in SYSTEM_FIELD_ORDER}


def table_name(cls_name: str) -> str:
    """``TodoLine`` -> ``todo_line``. Правило одно на все языки."""
    from .model.meta import table_name as _t

    return _t(cls_name)


def load():
    """Прочитать закреплённую таблицу. Ею пользуются сборка и тесты."""
    return json.loads(TABLE_PATH.read_text(encoding="utf-8"))
