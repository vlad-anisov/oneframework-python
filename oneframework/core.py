"""Где лежит ядро -- договор, сборщик и рантайм.

Привязке на питоне ядро нужно постоянно: собрать базу, напечатать план,
поднять `inspect`, запустить сборку. До сих пор каждое место знало путь само --
``КОРЕНЬ / "libs" / "js" / ...``, восемь раз в шести файлах. Внутри одного
дерева это работало и было незаметно; в разных репозиториях так нельзя, а
разъезжаются такие пути молча: правится одно место, ломается соседнее.

Порядок поиска -- от самого явного к самому удобному:

1. ``ONEFRAMEWORK_CORE`` -- сказали прямо, спорить не с чем;
2. пакет ``oneframework`` в ``node_modules`` -- обычная установка, когда
   привязка и ядро поставлены по отдельности;
3. соседний каталог в дереве разработки -- когда всё лежит вместе.

Не нашлось -- отказ, называющий все три места. «Ядро не найдено» без списка
заставляет угадывать между «не поставил», «поставил не туда» и «переменная
пуста».
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

from .errors import OneFrameworkError

ENV = "ONEFRAMEWORK_CORE"

#: Файл, по которому ядро узнаётся наверняка. Не `package.json`: его имя носит
#: и привязка на JavaScript, а вот сборщик базы есть только у ядра.
ПРИМЕТА = Path("src") / "build-db.mjs"

#: Раскладка дерева разработки: ядро лежит рядом, в `libs/js`.
РЯДОМ = Path(__file__).resolve().parents[1] / "libs" / "js"

_НАЙДЕНО: list[Path] = []


def корень() -> Path:
    """Каталог ядра. Ищется один раз за запуск."""
    if _НАЙДЕНО:
        return _НАЙДЕНО[0]

    # Названный и негодный путь -- отказ, а не переход к следующему месту. Тем
    # же доводом, что у ключа подписи: опечатка в переменной молча собрала бы
    # приложение **другим** ядром, и заметить подмену было бы негде.
    указано = os.environ.get(ENV)
    if указано:
        путь = Path(указано).expanduser()
        if not (путь / ПРИМЕТА).exists():
            raise OneFrameworkError(
                f"{ENV} указывает на {путь}, а ядра там нет: не нашлось "
                f"{ПРИМЕТА}.\nУберите переменную, чтобы искать обычным порядком, "
                "либо поправьте путь.")
        _НАЙДЕНО.append(путь)
        return путь

    искали = []
    for имя, путь in (("node_modules", _из_node_modules()), ("рядом в дереве", РЯДОМ)):
        искали.append(f"  {имя}: {путь or 'не нашлось'}")
        if путь and (путь / ПРИМЕТА).exists():
            _НАЙДЕНО.append(путь)
            return путь
    raise OneFrameworkError(
        "Ядро не найдено. Искали:\n" + "\n".join(искали)
        + f"\n\nПоставьте его -- `npm install oneframework` -- либо укажите "
        f"путь: {ENV}=/путь/к/ядру.\n"
        "Ядро написано на JavaScript и нужно только на машине сборки: на "
        "устройство едет собранное приложение, а не оно."
    )


def _из_node_modules():
    """Спросить node, где лежит пакет. Молчит, если node нет или пакета нет."""
    node = shutil.which("node")
    if not node:
        return None
    готово = subprocess.run(
        [node, "--input-type=module", "-e",
         # Разрешается точка входа пакета, а не его манифест: путь к манифесту
         # выглядит путём в дереве, и сторож ссылок (`tests/test_references.py`)
         # принимает его за файл, которого нет.
         "import { createRequire } from 'node:module';"
         " const r = createRequire(process.cwd() + '/');"
         " process.stdout.write(r.resolve('oneframework'));"],
        capture_output=True, text=True, encoding="utf-8")
    if готово.returncode != 0 or not готово.stdout.strip():
        return None
    # `index.mjs` лежит в корне пакета -- он и нужен.
    return Path(готово.stdout.strip()).parent


def файл(*части) -> Path:
    """Путь внутри ядра: ``core.файл("src", "build", "plan.mjs")``.

    Отказ, если такого файла нет: ядро нашлось, но не то -- это другая беда,
    чем «ядра нет», и путать их в одном сообщении значит гадать дважды.
    """
    путь = корень().joinpath(*части)
    if not путь.exists():
        raise OneFrameworkError(
            f"В ядре нет {Path(*части)}: {путь}\n"
            "Похоже, ядро другой версии. Обновите его вместе с привязкой."
        )
    return путь


def node() -> str:
    """`node` на машине сборки. Отказ вслух: без него ядро не запустить."""
    найден = shutil.which("node")
    if not найден:
        raise OneFrameworkError(
            "Ядро написано на JavaScript, а node нет. Поставьте node -- на "
            "устройство он не едет, нужен только на машине сборки.")
    return найден
