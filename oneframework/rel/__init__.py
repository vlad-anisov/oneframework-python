"""Реляционный слой: типизированное дерево -> параметризованный SQL.

Здесь живёт то, что решено 16.08.2026 (`docs/plan-logic.md`): логика хранится
данными, а исполняет её **SQLite -- но не он задаёт семантику**. Разница
принципиальна и стоит того, чтобы повторить её в первой строке модуля.

Если просто печатать SQL и смотреть, что вышло, то `1/0 -> NULL`, тихий переход
целого к плавающей точке при переполнении и `upper('чай') -> 'чай'` становятся
нашими правилами **случайно**. Поэтому компилятор здесь отвечает не «получилось
ли напечатать запрос», а «удалось ли сохранить объявленный смысл», и у каждого
перевода есть исход:

* :data:`EXACT_NATIVE` -- у SQLite ровно нужная семантика;
* :data:`EXACT_ADAPTED` -- смысл сохранён явными ``CAST``/``CASE``/``COALESCE``;
* :data:`UNSUPPORTED` -- точный перевод не построен, и это **отказ с именем
  недостающей операции**, а не молчаливая подмена.

Вторая разметка -- **форма исполнения** (:data:`ROW_SCALAR`, :data:`GROUPED`,
:data:`RELATIONAL`, :data:`RECURSIVE`). Без неё семантически безупречный
``Count`` превращается в 125 коррелированных подзапросов на экран: замерено, на
30 000 задач это 126 мс против 8,7 у слитой выборки.

Единица компиляции поэтому -- **выборка целиком**, а не отдельное поле. См.
:mod:`oneframework.rel.plan`.
"""

