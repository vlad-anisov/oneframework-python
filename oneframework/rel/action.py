#: Исполнители -- `wasm_action`, `js_action`, `python_action` и
#: `declarative_action` -- убраны 21.08.2026. Они были второй записью того, что
#: исполняет устройство (`libs/js/src/core/runtime/logic.js`), и на устройстве не
#: исполнялись ни разу. Правила, которые они держали, переехали на живую
#: половину: `tests/test_logic_host.py`.
#:
#: Осталось различение **формы** объявления: его спрашивает выкладка, решая,
#: что вообще класть в базу.
__all__ = ["is_declarative", "is_python", "is_js", "is_wasm"]


def is_declarative(doc):
    """Объявление это или имя точки входа в модуль. Различает **форма**."""
    return isinstance(doc, dict) and "entry" not in doc and (
        "rule" in doc or "write" in doc or is_python(doc) or is_js(doc)
        or is_wasm(doc))


def is_python(doc):
    """Действие, которое считает **настоящий питон на устройстве**.

    Третий вид объявления, и заведён он ради того, чего в SQL нет и не будет:
    словарной морфологии, разбора чужого формата, чтения документа. Всё
    остальное по-прежнему обязано быть правилом и правкой -- питон здесь не
    удобная лазейка, а ответ на «этого запросом не выразить».

    Едет он **исходником**, той же дорогой, что модели и виды. Не байтами:
    байты пришлось бы собирать, подписывать и сверять, а исходник читается
    глазами и приезжает тем же обменом.
    """
    return isinstance(doc, dict) and isinstance(doc.get("python"), dict) \
        and "source" in doc["python"]


def is_wasm(doc):
    """Действие, **скомпилированное** в WebAssembly.

    Третий способ запуска, и он отличается от двух других по существу: ни
    интерпретатора в поставке, ни исходника на устройстве -- туда едет модуль,
    и его инстанцирует движок, который в webview уже есть.

    Объявление называет **модуль**, а не текст: байты кладёт сборка, потому
    что 624 КБ машинного кода строкой в таблице определений возить незачем.
    """
    return isinstance(doc, dict) and isinstance(doc.get("wasm"), dict) \
        and "module" in doc["wasm"]




def is_js(doc):
    """Действие на JavaScript -- самая дешёвая из трёх дорог.

    Рантайма закладывать не надо: он уже стоит, это сам webview.

    Kotlin сюда **не** приезжает, хотя раньше здесь было написано обратное.
    `.kt` объявлен как ``wasm`` (`oneframework/device.py`): он компилируется
    TeaVM в WebAssembly и исполняется `libs/js/src/core/runtime/wasm_action.js`. Дорога
    через `kotlinc-js` разбиралась и отменена, её сборщик удалён 21.08.2026.

    ``language`` в объявлении говорит, чем действие написано, а не чем
    исполняется.
    """
    return isinstance(doc, dict) and isinstance(doc.get("js"), dict) \
        and "source" in doc["js"]


