"""Действие, объявленное данными: правило + запись, без единого байта кода.

Первое действие, ради которого больше не нужен модуль WASM. `Task.complete`
--- «завершить задачу вместе с подзадачами на любую глубину» --- считалось
случаем, который «декларацией не выражается»: так написано в шапке
`examples/logic/src/lib.rs`. Выражается: правило даёт множество, `Mutation`
его правит, и всё это один оператор SQL.

Замерено сверкой с модулем, пока тот был в дереве: набор и записанные строки
совпадали побайтно, включая его особенность --- уже выполненная подзадача
заслоняет своих невыполненных детей. И модуль, и сверку унесли вместе с
рантаймом WASM, так что это довод, а не сторож. Разница форм в том, что в
модуле это условие приходится вычитывать из цикла, а здесь оно стоит строкой
объявления.

Форма объявления::

    {"name": "Task.complete", "model": "Task",
     "rule":  {"name": "subtree", "table": "task", "via": "parent_id",
               "include_seed": True, "seed": {"param": "root"},
               "where": {"op": "not", "args": [{"field": "done"}]}},
     "write": {"table": "task", "source": "subtree",
               "set": {"done": {"const": True}}},
     "returns": [{"name": "completed", "type": "integer"}]}
"""

from __future__ import annotations

