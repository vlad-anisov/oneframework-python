"""Идентификатор записи, не зависящий от того, кто вставил первым.

``id INTEGER PRIMARY KEY AUTOINCREMENT`` -- счётчик, и счётчик у каждого свой.
Два устройства, поработав офлайн, оба выдадут ``5``, и при слиянии эти пятёрки
окажутся одной записью: не конфликт, не предупреждение, а молча неверный
результат. Поэтому ключ обязан быть глобально уникальным, и придумывать его
устройство должно само, никого не спрашивая.

Взят UUID седьмой версии (RFC 9562): первые 48 бит -- миллисекунды Unix, дальше
счётчик и случайность. Из этого следует свойство, на которое опирается весь
остальной код: **строковый порядок совпадает с порядком создания**. Значит
``ORDER BY id`` по-прежнему значит «в порядке добавления», списки не
переворачиваются, и ни один запрос переписывать не надо.

Случайный UUID4 этого свойства не имеет: индекс по нему разъезжается, а список
без явной сортировки перестаёт быть списком.
"""

from __future__ import annotations

import contextlib
import hashlib
import os
import time
import uuid as _uuid

__all__ = ["new_id", "is_id", "uuid7", "seeded_ids"]

#: Сколько бит выделено под счётчик внутри одной миллисекунды.
_COUNTER_BITS = 12
_COUNTER_MAX = (1 << _COUNTER_BITS) - 1

_last_ms = 0
_counter = 0


def _uuid7_local() -> _uuid.UUID:
    """UUIDv7 своими руками -- для рантаймов старше 3.14.

    Монотонность внутри миллисекунды держится счётчиком в ``rand_a``: без него
    две записи, созданные в одну миллисекунду, встали бы в случайном порядке, и
    список, добавленный из seed-а одним циклом, показался бы перемешанным.
    """
    global _last_ms, _counter

    ms = time.time_ns() // 1_000_000
    if ms > _last_ms:
        _last_ms, _counter = ms, 0
    else:
        _counter += 1
        if _counter > _COUNTER_MAX:
            # Счётчик кончился -- занимаем следующую миллисекунду. Часы её
            # догонят; порядок при этом не ломается.
            _last_ms, _counter = _last_ms + 1, 0
        ms = _last_ms

    rand_b = int.from_bytes(os.urandom(8), "big") & ((1 << 62) - 1)
    value = (
        (ms & ((1 << 48) - 1)) << 80
        | 0x7 << 76
        | _counter << 64
        | 0b10 << 62
        | rand_b
    )
    return _uuid.UUID(int=value)


#: ``uuid.uuid7`` появился в стандартной библиотеке 3.14 (Pyodide у нас 3.14.2).
#: Там он тоже монотонный, поэтому берётся как есть, а свой остаётся для 3.10--3.13.
uuid7 = getattr(_uuid, "uuid7", _uuid7_local)


#: Откуда берутся ключи прямо сейчас. Обычно ниоткуда -- берётся время; на
#: время посева подменяется на постоянный поток (см. `seeded_ids`).
_источник = None

#: Мгновение, от которого отсчитываются ключи посева. Постоянное и заведомо
#: раннее: демонстрационные записи должны стоять раньше всего, что человек
#: заведёт сам. 1 января 2020 года.
_ПОСЕВ_MS = 1_577_836_800_000


def new_id() -> str:
    """Новый ключ записи -- строкой, потому что строкой он и хранится."""
    if _источник is not None:
        return _источник()
    return str(uuid7())


@contextlib.contextmanager
def seeded_ids(поток: str):
    """Внутри -- ключи посева: одни и те же на всякой сборке.

    Зачем. Сборка заводит базу-заготовку заново, и посев в ней получал свежие
    случайные ключи. Всякий новый клиент ставил себе эту заготовку и отправлял
    её на обмен как **новые** записи -- сервер честно складывал их рядом с уже
    лежащими. На стенде за день так набралось восемь копий каждого списка и
    каждой задачи: восемь раз кто-то заходил с чистого профиля.

    Ключ здесь выводится из имени потока и порядкового номера, а не из часов и
    случайности. Форма остаётся семёркой (`uuid7`), и порядок сохраняется:
    номер ложится в тот же счётчик, которым держится монотонность внутри
    миллисекунды. Значит два клиента, поставившие заготовку порознь, привезут
    одни и те же записи, и обмен сведёт их в одну.
    """
    global _источник
    номер = 0

    def следующий() -> str:
        nonlocal номер
        ms = _ПОСЕВ_MS + (номер >> _COUNTER_BITS)
        счёт = номер & _COUNTER_MAX
        зерно = hashlib.sha256(f"{поток}\0{номер}".encode("utf-8")).digest()
        rand_b = int.from_bytes(зерно[:8], "big") & ((1 << 62) - 1)
        номер += 1
        return str(_uuid.UUID(int=(
            (ms & ((1 << 48) - 1)) << 80
            | 0x7 << 76
            | счёт << 64
            | 0b10 << 62
            | rand_b
        )))

    прежний, _источник = _источник, следующий
    try:
        yield
    finally:
        _источник = прежний


def is_id(value) -> bool:
    """Похоже ли значение на наш ключ. Нужно миграции, чтобы отличить
    уже переехавшую базу от той, где ``id`` ещё число."""
    if not isinstance(value, str) or len(value) != 36:
        return False
    try:
        _uuid.UUID(value)
    except ValueError:
        return False
    return True
