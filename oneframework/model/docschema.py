"""Рубеж на выкладке: документ вида обязан сходиться с договором.

До 20.08.2026 рубежа не было ни одного. ``put()`` принимала что угодно: любой
словарь ложился в ``_oneframework_def`` и уезжал обменом на устройства. Найдено
разбором со стороны, и правильно найдено -- определение это **исполняемая
настройка**, и подпись издателя отвечает за то, *кто* её прислал, а не за то,
*что* прислано.

Договор -- ``protocol/document.json``. Он порождён из живых документов, то есть
описывает то, что рантайм правда рисует; значит расхождение с ним -- это узел,
которого отрисовка не знает, или узел без обязательного ключа. И то и другое на
устройстве выглядит одинаково: пустое место вместо части экрана, без единого
слова.

Чего этот рубеж **не** делает и не может: он не проверяет значения. Домен,
собранный неверно, форму пройдёт -- за это отвечает `rel/`. Здесь только форма.
"""

from __future__ import annotations

import json
from pathlib import Path

CONTRACT_PATH = Path(__file__).resolve().parents[2] / "protocol" / "document.json"

_КОНТРАКТ = None


def contract():
    """Договор, прочитанный один раз за процесс."""
    global _КОНТРАКТ
    if _КОНТРАКТ is None:
        _КОНТРАКТ = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    return _КОНТРАКТ


def _узлы(node, путь="doc", где="nodes"):
    """Обход всего документа: путь, узел и то, чем его мерить.

    Мерило переключается ключом `action`: всё под ним -- действие, а действия
    договор описывает отдельным словарём.
    """
    if isinstance(node, dict):
        if isinstance(node.get("type"), str):
            yield путь, node, где
        for ключ, значение in node.items():
            yield from _узлы(значение, f"{путь}.{ключ}",
                             "actions" if ключ == "action" else где)
    elif isinstance(node, list):
        for i, item in enumerate(node):
            yield from _узлы(item, f"{путь}[{i}]", где)


def problems(doc, contract_=None):
    """Чем документ расходится с договором. Пустой список -- сходится.

    Список, а не первое попавшееся: пересобирающий вид хочет видеть всё разом,
    а не чинить по одному расхождению за прогон.
    """
    договор = contract_ or contract()
    # Узлы и действия договор описывает **порознь**, и различает их не тип, а
    # место: действие лежит под ключом `action`. Первая редакция этого файла
    # мерила действия формами узлов -- и объявила расхождением все 29 видов
    # всех примеров.
    формы = {"nodes": договор["nodes"], "actions": договор["actions"]}
    беды = []
    for путь, узел, где in _узлы(doc):
        тип = узел["type"]
        форма = формы[где].get(тип)
        если_нет = "действие" if где == "actions" else "узел"
        if форма is None:
            беды.append(f"{путь}: {если_нет} типа {тип!r} договору неизвестен")
            continue
        нет = [к for к in форма["required"] if к not in узел]
        if нет:
            беды.append(
                f"{путь}: у {если_нет}а {тип!r} нет обязательных ключей: "
                f"{', '.join(sorted(нет))}",
            )
    return беды
