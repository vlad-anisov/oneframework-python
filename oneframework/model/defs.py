"""Определения приложения как записи в базе.

База -- источник правды не только для данных, но и для того, из чего
приложение состоит: моделей, полей, видов, действий. Зачем:

* **Синхронизации появляется предмет.** Определения лежат в обычной таблице,
  значит уезжают на сервер и приезжают обратно тем же механизмом, что и задачи
  -- без отдельного канала и особого случая.
* **Появляется версия.** У каждого определения есть отпечаток содержимого, и
  видно, изменилось ли оно. Это то, чего сейчас нет вовсе и без чего доставка
  видов по сети превращается в пустой экран без диагностики.
* **Появляется проверяемость.** Определение стало данными, значит его можно
  выгрузить, сравнить две версии и отдать другому бэкенду.

Отпечаток -- sha256 от канонического JSON (ключи отсортированы). Одинаковое
определение даёт одинаковый отпечаток на любой машине и в любом языке, поэтому
по нему можно решать «слать или не слать», не сравнивая содержимое целиком.

**Как именно он считается, здесь не записано.** Считает ядро, одной
реализацией на все языки: записанное дважды совпадало бы ровно на тех случаях,
которые кто-то догадался проверить.
"""

from __future__ import annotations

import json

# Каноническая запись и отпечаток -- местные, без WASM: правило вернулось в
# оба языка, а сторожит его RFC 8785 и сверка питона с JavaScript.
from .schema import model_schema, type_schema
from . import docschema

__all__ = ["DEF_TABLE", "DEF_COLUMNS", "KINDS", "SKIPPED", "model_defs", "view_defs"]

DEF_TABLE = "_oneframework_def"

#: Раскладка таблицы определений: имя колонки, тип, остальное объявление.
#: Одно объявление и на DDL, и на отпечаток схемы. Разойдись они -- страж
#: перестал бы замечать перестановку колонок ровно в той таблице, ради которой
#: он и сторожит: changeset ложится по НОМЕРУ колонки, и переставленные колонки
#: дают не отказ, а тихую порчу.
DEF_COLUMNS = (
    ("kind", "TEXT", "NOT NULL"),
    ("name", "TEXT", "NOT NULL"),
    ("fingerprint", "TEXT", "NOT NULL"),
    ("doc", "TEXT", "NOT NULL"),
    ("revision", "INTEGER", "NOT NULL DEFAULT 1"),
    ("hlc", "TEXT", "NOT NULL DEFAULT ''"),
)

#: Виды определений. Список закрытый: если понадобится новый, он должен быть
#: добавлен осознанно, иначе таблица превратится в свалку.
KINDS = ("types", "model", "view", "action")












def model_defs(models):
    """Определения моделей как данные: ``[(вид, имя, документ), ...]``.

    Собрать документ и положить его в базу -- разные работы. Вторую делает
    сборщик (`libs/js/src/build-db.mjs`) тем же кодом, каким пишет базу
    устройство; питон знает только, **что** класть.
    """
    models = list(models)
    docs = [type_schema(models)] + [model_schema(m) for m in models]
    # Вся выкладка -- один переход границы, а не по одному на определение.
    # Переход стоит на порядки дороже самой работы (docs/wasm-api.md, §7), и
    # прогрев укладывает их все в один, не трогая сигнатуру `put`.
    return [("types", "_", docs[0])] + [
        ("model", m.__name__, d) for m, d in zip(models, docs[1:])
    ]




#: Почему вид не выложен. Ключ -- имя вида, значение -- причина строкой.
#: Заполняется каждой публикацией заново, читается ``oneframework check`` и тестами:
#: пропуск обязан быть виден снаружи, а не только в отладчике.
SKIPPED: dict[str, str] = {}




def view_defs(views):
    """Документы видов как данные -- пара к :func:`model_defs`.

    Пропуск непереехавшего вида -- здесь же: он часть ответа «что выкладывать»,
    а не записи. Причина пишется в :data:`SKIPPED` независимо от того, кто потом
    возьмётся класть.
    """
    from ..ui.view import document

    SKIPPED.clear()
    ready = []
    for view in views:
        try:
            doc = document(view)
        except Exception as exc:
            SKIPPED[view.__name__] = f"{type(exc).__name__}: {exc}"
            continue
        # Рубеж на форме, и стоит он **здесь**, а не при записи. Определение --
        # исполняемая настройка, и подпись издателя отвечает за то, *кто* её
        # прислал, а не за то, *что* прислано. Узел, которого отрисовка не
        # знает, выглядит на устройстве пустым местом вместо части экрана -- и
        # молчит. Стоит он на форме, а не при записи: базу пишет сборщик на
        # JS, и рубеж при записи обходился бы стороной.
        беды = docschema.problems(doc)
        if беды:
            raise ValueError(
                f"Документ вида {view.__name__!r} не сходится с "
                "protocol/document.json:\n  " + "\n  ".join(беды),
            )
        ready.append(("view", view.__name__, doc))

    return ready


