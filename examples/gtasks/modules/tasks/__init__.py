#: Бизнес-логика этого модуля -- скомпилированный WASM и то, что он умеет.
#: Объявляется здесь же, где ``DEPENDS``, и по той же причине: файла-манифеста
#: у модуля нет и заводить его ради одного списка не стоит.
#:
#: Путь ведёт к общему артефакту `examples/logic/`, а не к копии рядом:
#: скомпилированный модуль -- вывод сборки, и вторая его копия в дереве
#: устареет молча.
#:
#: Три объявления на один модуль -- не три модуля: точка входа принадлежит
#: модулю, а не наоборот, и тело лежит в базе один раз.
#: Модуля здесь больше нет. Оба действия, ради которых он существовал,
#: оказались выразимы **данными**:
#:
#: * готовность списка -- объявлением вычисляемого поля (см. `models.py`);
#: * «завершить с подзадачами» -- правилом плюс правкой, ниже.
#:
#: Шапка `examples/logic/src/lib.rs` называла оба «тем, что декларацией не
#: выражается». Сверка с модулем, пока тот был в дереве, показала обратное:
#: набор и записанные строки совпадали, включая его особенность -- уже
#: выполненная подзадача заслоняет своих невыполненных детей. Саму сверку
#: унесли вместе с рантаймом WASM, поэтому здесь её и не назвать.
LOGIC = [{
    "actions": [
        {
            "name": "Task.complete", "model": "Task",
            "label": "Выполнить с подзадачами",
            "args": [{"name": "ids", "type": "ids"}],
            "returns": [{"name": "changed", "type": "integer"}],
            # Правило даёт множество: сама задача и её невыполненные потомки на
            # любую глубину. Условие «не выполнена» стоит здесь строкой -- в
            # модуле его приходилось вычитывать из цикла.
            #
            # Неподвижная точка считается только по ключу: кольцо в данных
            # заводится само (спор решается по колонкам, и два устройства могут
            # назначить друг друга родителями), а с ключом расчёт на кольце
            # завершается.
            "rule": {
                "name": "subtree", "table": "task", "via": "parent_id",
                "include_seed": True, "seed": {"param": "root"},
                "where": {"op": "not", "args": [{"field": "done"}]},
            },
            # Правка применяется к тому множеству, что дало правило. Про
            # потомков и графы она не знает ничего -- ради этого специального
            # `write_recursive` в языке и нет.
            "write": {
                "table": "task", "source": "subtree",
                # Дата приходит **параметром вызова**: `datetime('now')` внутри
                # запроса SQLite сама объявляет недетерминированной, и два
                # устройства разошлись бы, посчитав в разные секунды.
                "set": {"done": {"const": True}, "finished": {"param": "today"}},
            },
        },
        # Третий вид объявления: считает **настоящий питон на устройстве**.
        #
        # Заведён ради того, чего в SQL нет и не будет. «задачами -> задача»
        # знает словарь русского языка, а не правило: тут нет ни окончания, по
        # которому это выводится, ни таблицы, по которой это ищется запросом.
        # Всё, что выразимо запросом, обязано остаться правилом и правкой --
        # питон здесь ответ на «этого не выразить», а не удобная лазейка.
        #
        # Исходник едет той же дорогой, что модели и виды, и читается глазами.
        # Библиотеки объявлены в `app.py` и лежат в сборке: у пользователя
        # webview может быть без сети.
        {
            "name": "Board.normalize", "model": "Board",
            "label": "Привести название к начальной форме",
            "args": [{"name": "ids", "type": "ids"}],
            "returns": [{"name": "records", "type": "json"}],
            "python": {
                "entry": "нормализовать",
                # Что действию позволено записать. Список закрытый: питон
                # считает, а пишет хост, и записать он может ровно названное.
                "writes": ["name"],
                "source": (
                    "import pymorphy3\n"
                    "\n"
                    "morph = pymorphy3.MorphAnalyzer()\n"
                    "\n"
                    "\n"
                    "def нормализовать(кадр):\n"
                    "    готово = []\n"
                    "    for запись in кадр.get('records', []):\n"
                    "        слова = (запись.get('name') or '').split()\n"
                    "        начальные = ' '.join(\n"
                    "            morph.parse(с)[0].normal_form for с in слова)\n"
                    "        готово.append({'id': запись['id'], 'name': начальные})\n"
                    "    return {'records': готово}\n"
                ),
            },
        },
    ],
}]
