"""Тест, названный в комментарии сторожем, обязан существовать.

Комментарии здесь ссылаются на тесты: «сторожит ``tests/test_protocol.py``»,
«закреплено ``tests/js/wire.test.mjs``». Ссылка -- не украшение: она избавляет
читателя от необходимости верить комментарию на слово, он идёт и смотрит.

Гниёт она молча. Тест переименовали или унесли вместе с куском системы, а
строчка осталась и на вид ничем не отличается от рабочей: читатель узнаёт об
этом, только сходив по ней. Так и было -- ``oneframework/declaration.py``
отправлял за доказательством к файлу, которого в дереве не было вовсе, а
шесть ссылок пережили унесённый рантайм WASM.

Проверяется ровно одно: названный файл есть. Тот ли это тест и то ли он
сторожит, машине не видно и остаётся делом чтения. Но удаление теста после
этого громкое, а на глаз оно неотличимо от порядка.

``docs/`` сюда не входит: там записано, как было, и имена унесённых тестов
стоят в тех записях законно.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Код и договоры -- всё, что описывает сегодняшнее устройство, а не прошлое.
КОРНИ = ("oneframework", "libs", "web/src", "protocol", "examples", "tests")
СУФФИКСЫ = {".py", ".mjs", ".js", ".kt", ".json"}

#: Суффикс не требуется: тест зовут и файлом, и голым именем -- ссылка та же.
#: Вторая половина -- проверки на JavaScript: они называются иначе, и без неё
#: ссылка на удалённый `tests/js/*.test.mjs` гнила бы молча.
ССЫЛКА = re.compile(r"tests/test_[a-z0-9_]+|tests/js/[a-z0-9-]+\.test\.mjs")

#: Путь к файлу исходника, названный в комментарии: «пара к
#: `oneframework/model/fields.py`», «см. `libs/js/src/core/runtime/db.js`». Гниёт он так
#: же молча, как ссылка на тест, и за один день я ловил такую гниль
#: руками трижды -- удалённый файл продолжали называть парой, близнецом и
#: местом, где что-то лежит. Машина это видит, а глаз нет.
#: Порядок расширений в переборе значим: `js` совпал бы с началом `json`, и
#: `protocol/document.json` читался бы как несуществующий `document.js`. Длинные
#: идут первыми, а `(?![\w.])` не даёт откусить хвост.
ПУТЬ = re.compile(
    r"\b((?:oneframework|libs|web/src|protocol)/[A-Za-z0-9_/-]+"
    r"\.(?:json|jsx|mjs|py|js|kt))(?![\w.])")


def исходники():
    for корень in КОРНИ:
        for путь in sorted((ROOT / корень).rglob("*")):
            if путь.suffix not in СУФФИКСЫ or not путь.is_file():
                continue
            if {"node_modules", "__pycache__"} & set(путь.parts):
                continue
            yield путь


def test_no_root_is_read_as_empty():
    """Переименуют корень -- обход опустеет, а сторож станет вечно зелёным.

    Числом файлов это не проверить: их количество меняется каждую неделю, и
    порог пришлось бы двигать следом. Проверяется, что каждый названный
    корень дал хоть что-то.
    """
    прочитано = list(исходники())
    пусто = [корень for корень in КОРНИ
             if not any(файл.is_relative_to(ROOT / корень) for файл in прочитано)]
    assert not пусто, f"корни, из которых не прочитано ни файла: {пусто}"


def test_every_test_named_as_a_guard_exists():
    """Все ссылки разом, а не первая: чинит их один заход, а не шесть."""
    пропали = []
    for путь in исходники():
        строки = путь.read_text(encoding="utf-8").splitlines()
        for номер, строка in enumerate(строки, 1):
            for имя in ССЫЛКА.findall(строка):
                if not (ROOT / (имя if имя.endswith(".mjs") else f"{имя}.py")).exists():
                    пропали.append(f"{путь.relative_to(ROOT)}:{номер} -> {имя}")
    assert not пропали, "названы сторожами, а их нет: " + "; ".join(пропали)


def test_every_source_named_in_a_comment_exists():
    """Файл, названный в комментарии, обязан существовать.

    Комментарии зовут соседей по имени: «пара к `oneframework/model/ids.py`»,
    «см. `libs/js/src/core/runtime/db.js`». Удали соседа -- и строчка остаётся, ничем на
    вид не отличаясь от рабочей. Читатель узнаёт об этом, только сходив по ней.

    За один день такая гниль ловилась руками трижды: `db.js` звал
    парой удалённый `storage.py`, `hlc.js` -- удалённый `hlc.py`, карта в
    `docs/wasm-api.md` называла пять удалённых файлов текущими. Сторож ссылок
    этого не видел -- он сверял только имена проверок. Теперь видит.

    Прошлое называть можно, но **вслух**: строка с «удал», «жил здесь», «было
    парой» пропускается. Так запись истории остаётся законной, а недосмотр --
    нет.
    """
    #: Прошлое называть можно, если сказано вслух. Многоточие в пути -- не путь,
    #: а сокращение в прозе (`libs/kotlin/.../Expr.kt`), и его тоже пропускаем.
    ПРОШЛОЕ = ("удал", "жил здесь", "жила здесь", "стояли", "стояла", "было парой",
               "была парой", "был близнецом", "прежде", "раньше здесь", "/...")
    мёртвые = []
    for путь in исходники():
        for н, строка in enumerate(путь.read_text(errors="ignore").splitlines(), 1):
            if any(с in строка.lower() for с in ПРОШЛОЕ):
                continue
            for названный in ПУТЬ.findall(строка):
                if not (ROOT / названный).exists():
                    мёртвые.append(f"{путь.relative_to(ROOT)}:{н} -> {названный}")
    assert not мёртвые, "названы в комментариях, а их нет:\n  " + "\n  ".join(мёртвые)
