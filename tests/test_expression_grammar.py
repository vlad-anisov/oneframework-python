"""Грамматика выражений -- одна, и это сторож при ней.

Дерево выражения ездит между тремя языками объявления и двумя вычислителями.
Разойдись стороны в форме узла -- и он приезжает не ошибкой, а не тем условием,
то есть не тем списком на экране. Заметить это можно только по чужой жалобе.

Описание одно -- ``protocol/expression.json``, -- и теперь оно **источник**, а
не вывод. Прежде его порождал питон из своих классов, и это было верно ровно
пока питон умел строить каждый узел; выражения пишутся строкой, дерево из неё
собирает разборщик ядра, и порождать описание из питоновских классов стало
нечем. Файл читают все, и сверяются с ним тоже все.

Сторожа ловят разные способы разойтись:

1. **образец против самого себя** -- по образцу узел узнаётся однозначно;
2. **настоящие приложения против файла** -- дерево, которое правда доезжает до
   устройства, договору отвечает целиком;
3. **слова арифметики против компилятора** -- слово, которое разборщик умеет
   породить, а SQL перевести не умеет, откажет уже у человека;
4. **библиотека для JavaScript против образцов** -- тот же узел собрался другой
   записью. Сверяется побайтно: «похоже» здесь не значит ничего.

Отдельно проверяется, что сторож умеет ругаться: описание, по которому не
падает ни одно испорченное дерево, не проверяет ничего.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

from jsrel import call

ROOT = Path(__file__).resolve().parents[1]
DRIVER = ROOT / "tests" / "parity" / "expr_grammar_driver.mjs"
ГРАММАТИКА = json.loads(
    (ROOT / "protocol" / "expression.json").read_text(encoding="utf-8"))

#: Приложения, чьи выражения проверяются целиком. Настоящие, а не собранные из
#: тех же образцов, из которых написан файл: иначе сторож сверял бы описание
#: сам с собой.
ПРИМЕРЫ = ["todo", "gtasks", "kitchen", "showcase"]


# --------------------------------------------------------------------------
# сверщик дерева с описанием
# --------------------------------------------------------------------------
def узнать(узел):
    """Какой род договора описывает этот узел. ``None`` -- ни один.

    По ключам, а не по значению: род и есть набор ключей, и различать их
    иначе значило бы завести второе правило о том, что такое узел.
    """
    if not isinstance(узел, dict):
        return None
    ключи = set(узел)
    for имя, описание in ГРАММАТИКА["nodes"].items():
        обязательные = {к for к, о in описание["keys"].items() if not о.get("optional")}
        все = set(описание["keys"])
        if not обязательные <= ключи <= все:
            continue
        # Ключ с закрытым списком значений входит в опознание: `{"op": "&"}` и
        # `{"op": "="}` -- разные роды при одинаковых ключах.
        for к, о in описание["keys"].items():
            if "one_of" in о and к in узел and узел[к] not in о["one_of"]:
                break
        else:
            return имя
    return None


def беды(узел, путь="выражение"):
    """Всё, чем дерево расходится с описанием. Пусто -- значит отвечает."""
    if isinstance(узел, (str, int, float, bool)) or узел is None:
        return []
    if not isinstance(узел, dict):
        return [f"{путь}: {type(узел).__name__} -- не узел выражения"]
    род = узнать(узел)
    if род is None:
        return [f"{путь}: ни один род договора не описывает {sorted(узел)}"]
    описание = ГРАММАТИКА["nodes"][род]["keys"]
    найдено = []
    for ключ, значение in узел.items():
        о = описание[ключ]
        если = f"{путь}.{ключ}"
        if о.get("name") and not isinstance(значение, str):
            найдено.append(f"{если}: имя пишется строкой, а тут {значение!r}")
        elif о.get("expr"):
            найдено += беды(значение, если)
        elif о.get("exprs"):
            if not isinstance(значение, list):
                найдено.append(f"{если}: ждали список выражений")
            else:
                for i, ч in enumerate(значение):
                    найдено += беды(ч, f"{если}[{i}]")
    return найдено


# --------------------------------------------------------------------------
# сторожа
# --------------------------------------------------------------------------
@pytest.mark.parametrize("род", sorted(ГРАММАТИКА["nodes"]))
def test_образец_узнаётся_своим_родом(род):
    """Формы обязаны различаться: по образцу род узнаётся однозначно."""
    образец = ГРАММАТИКА["nodes"][род]["sample"]
    assert узнать(образец) == род
    assert беды(образец) == []


@pytest.mark.parametrize("пример", ПРИМЕРЫ)
def test_выражения_настоящего_приложения_отвечают_договору(пример):
    """Каждое выражение, доезжающее до устройства, обязано отвечать описанию.

    Спрашивается **план**: до него выражения записаны строкой, а в базу и на
    устройство едет то, что собрал разборщик. Сторожить надо именно это.
    """
    узел = shutil.which("node")
    if узел is None:
        pytest.skip("node на этой машине нет")
    команда = ROOT / "libs" / "js" / "bin" / "oneframework.mjs"
    пакет = subprocess.run(
        [узел, str(команда), "declare", str(ROOT / "examples" / пример / "app.py")],
        capture_output=True, text=True, cwd=str(ROOT))
    assert пакет.returncode == 0, пакет.stderr
    скрипт = (
        "import { buildPlan } from './libs/js/src/build/plan.mjs';"
        "let s='';process.stdin.on('data',c=>s+=c).on('end',()=>"
        "process.stdout.write(JSON.stringify(buildPlan(JSON.parse(s)))));")
    прогон = subprocess.run([узел, "--input-type=module", "-e", скрипт],
                            input=пакет.stdout, capture_output=True, text=True,
                            cwd=str(ROOT))
    assert прогон.returncode == 0, прогон.stderr
    план = json.loads(прогон.stdout)

    #: Ключи, за которыми в документе лежит выражение. Названы поимённо: обход
    #: «всё, что похоже на узел» принял бы за выражение любой словарь и молча
    #: перестал бы проверять то, ради чего заведён.
    КЛЮЧИ = {"visible", "enabled", "domain", "compute", "value", "when"}
    сколько, найдено = 0, []
    def обойти(что, путь):
        nonlocal сколько
        if isinstance(что, dict):
            for к, з in что.items():
                if к in КЛЮЧИ and isinstance(з, dict):
                    сколько += 1
                    найдено.extend(беды(з, f"{путь}.{к}"))
                else:
                    обойти(з, f"{путь}.{к}")
        elif isinstance(что, list):
            for i, э in enumerate(что):
                обойти(э, f"{путь}[{i}]")

    обойти(план["defs"], пример)
    assert not найдено, "\n".join(найдено)
    # Иначе проверка зеленела бы на приложении без единого выражения.
    assert сколько, f"{пример}: ни одного выражения не найдено -- обход сломан"


@pytest.mark.parametrize("слово", ГРАММАТИКА["nodes"]["arith"]["keys"]["op"]["one_of"])
def test_компилятор_знает_каждое_слово_арифметики(слово):
    """Слово языка без перевода в SQL -- отказ уже на устройстве, у человека."""
    call("compile_expr", {"op": слово, "args": [1, 2, 3]})


@pytest.mark.parametrize("испорченное", [
    {"field": "тег"},                       # запись компилятора, не языка
    {"op": "не-слово-языка", "args": [1]},  # слова такого нет
    {"op": "=", "l": {"r": "тег"}},         # сравнение без правой стороны
    {"r": 3},                               # имя не строкой
    {"agg": "count"},                       # свёртка без модели
    {"unset": True, "r": "тег"},            # два узла в одном
])
def test_сторож_умеет_отказать(испорченное):
    """Сторож, который не ругается ни на что, не сторожит ничего."""
    assert беды(испорченное)


@pytest.mark.skipif(shutil.which("node") is None, reason="node недоступен")
def test_javascript_собирает_те_же_узлы():
    """Библиотека на JavaScript обязана собирать те же узлы теми же записями."""
    прогон = subprocess.run(
        ["node", str(DRIVER)], input=json.dumps(ГРАММАТИКА, ensure_ascii=False),
        capture_output=True, text=True, check=True,
    )
    ответ = json.loads(прогон.stdout)

    assert ответ["refused"] == {}, "конструктор есть, а узел не собрался"
    for род, собранное in ответ["built"].items():
        assert беды(собранное) == []
        assert собранное == ГРАММАТИКА["nodes"][род]["sample"], (
            f"узел {род} на JavaScript записан иначе, чем в грамматике")
    # Не «сколько-нибудь», а поимённо: драйвер, разучившийся собирать, иначе
    # прошёл бы молча и не проверив ничего. Список короткий не по бедности:
    # условие пишется строкой, и своих сравнений у привязки нет ни у одной --
    # ни у питона, ни у JavaScript, ни у Kotlin.
    assert set(ответ["built"]) >= {"record_ref", "view_ref", "item_ref",
                                   "order", "text"}
    assert ответ["unknown"]["refused"], (
        "чужой узел обязан отказать вслух: молча доехавшее не то условие "
        f"показывает не те записи, а тут вышло {ответ['unknown'].get('value')!r}")
