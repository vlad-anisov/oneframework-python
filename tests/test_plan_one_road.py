"""Пакет объявления несёт всё, что знает приложение.

Замысел раскола такой: ядро (договор, сборка, рантайм) отдельно, а привязка
языка -- Python, JavaScript, Kotlin -- только печатает пакет объявления.
Держится он на одном: пакет несёт всё, что нужно сборке. Если питоновское
приложение знает хоть что-то сверх своего же напечатанного пакета, значит
привязка передаёт это мимо договора, и ядро без неё соберёт другое приложение.

Прежде у плана было две дороги -- у приложения он брал объекты, у
пакета читал документы. Они молча сходились; питоновскую дорогу убрали, и
План принимает только пакет.

Тогда встал вопрос, чем сверять: сравнивать пакет с самим собой -- пустая
работа. Сверяем со **вторым счётом** -- `model_defs`, `view_defs`, `app_schema`
считают то же самое прямо по питоновским объектам, не заглядывая в пакет. Это и
есть их работа теперь: независимое мнение, которое держит печать пакета
честной. Пропадёт второй счёт -- пропадёт и проверка.

Каждый пример -- **отдельным процессом**, по тому же доводу, что в
``test_build_db.py`` и ``test_document.py``: реестр моделей глобален и
ключуется именем класса, а посев примера ввозит свой ``app`` по-настоящему.
Загрузи два примера в один процесс -- и посев запишет строки в классы соседа,
причём молча.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

from oneframework.ui.view import View

ROOT = Path(__file__).resolve().parents[1]
ПРИМЕРЫ = sorted(p.parent.name for p in ROOT.glob("examples/*/app.py"))

_СВЕРКА = r"""
import json, sys
from pathlib import Path

корень, пример = sys.argv[1], sys.argv[2]
sys.path.insert(0, корень)
# Каталог проверок -- ради `conftest`: план считает ядро, и зовут его оттуда.
sys.path.insert(0, str(Path(корень) / "tests"))
sys.path.insert(0, str(Path(корень) / "examples" / пример))

import app as модуль
try:
    import seed as модуль_посева
    посев = getattr(модуль_посева, "seed", None)
except ImportError:
    посев = None

from conftest import план
from oneframework.declaration import Bundle, declare, record_seeds
from oneframework.model.defs import model_defs, view_defs
from oneframework.model.schema import app_schema

приложение = модуль.app
# Через текст JSON намеренно: пакет едет строкой, и всё, что до неё не
# доживает, до устройства тоже не доедет.
план = план(Bundle(json.loads(json.dumps(declare(приложение, посев)))))

ключ = lambda d: (d[0], d[1])
свой = ([list(t) for t in model_defs(приложение.models)]
        + [list(t) for t in view_defs(приложение.views)])
# Из **пакета**, а не из плана. План -- это уже работа ядра: оно разворачивает
# выражения, записанные строкой, и сверять с ним питоновский счёт значило бы
# мерить разворот, а не согласие двух дорог. Согласие -- вот оно: `declare`
# и `view_defs` обязаны дать одни и те же определения.
пакет = Bundle(json.loads(json.dumps(declare(приложение, посев))))
из_пакета = ([["types", "_", пакет.doc["types"]]]
             + [["model", м["name"], м] for м in пакет.doc["models"]]
             + [["view", в["name"], в] for в in пакет.doc["views"]])

print(json.dumps({
    "схема_из_пакета": план["schema"],
    "схема_вторым_счётом": app_schema(приложение),
    "defs_из_пакета": sorted(из_пакета, key=ключ),
    "defs_вторым_счётом": sorted(свой, key=ключ),
    "посев_из_пакета": план["seeds"],
    "посев_вторым_счётом": record_seeds(приложение, посев),
}, ensure_ascii=False, default=str))
"""


@pytest.fixture(scope="module", params=ПРИМЕРЫ)
def сверка(request):
    готово = subprocess.run([sys.executable, "-c", _СВЕРКА, str(ROOT), request.param],
                            capture_output=True, text=True, encoding="utf-8", cwd=str(ROOT))
    assert готово.returncode == 0, готово.stderr
    return json.loads(готово.stdout)


def test_схема_в_пакете_та_же(сверка):
    assert (без_тела_формулы(сверка["схема_из_пакета"])
            == без_тела_формулы(сверка["схема_вторым_счётом"]))


def без_тела_формулы(о):
    """Заменить тело `compute` меткой -- сохранив само его наличие.

    Питоновский счёт видит формулу так, как её написали, -- строкой; ядро
    разворачивает её в дерево. Сравнивать эти два вида значило бы мерить работу
    разворота, а она сторожится отдельно (`tests/js/expr-text-wire.test.mjs`).
    Здесь сверяется то, что обе стороны правда обязаны знать одинаково: какие
    модели, таблицы и колонки, и у каких полей формула **есть**. Потеря формулы
    от этого не спрячется -- пропадёт метка.
    """
    if isinstance(о, dict):
        return {к: ("<формула>" if к == "compute" else без_тела_формулы(з))
                for к, з in о.items()}
    if isinstance(о, list):
        return [без_тела_формулы(э) for э in о]
    return о


def test_определения_в_пакете_те_же(сверка):
    # Целиком, вместе с телами: совпадения имён мало -- тело вида и есть то,
    # что уедет на устройство. `model_defs` отдаёт и запись «types», поэтому
    # с обеих сторон отброшены только действия: они приезжают разделом «logic».
    assert сверка["defs_из_пакета"] == сверка["defs_вторым_счётом"]


def test_посев_доезжает_пакетом(сверка):
    # Раньше посев пакетом не выражался вовсе, и сборка из `.json` отказывалась
    # вслух: собрать то же приложение без питона было нельзя.
    assert сверка["посев_из_пакета"] == сверка["посев_вторым_счётом"]


class _Пусто(View):
    """Корневой вид на уровне модуля: виды приложение находит обходом пакета."""

    def ui(self, record):
        return ()


def test_приложение_в_план_больше_не_ходит():
    """Дорога одна. Питоновский объект обязан получить отказ вслух.

    Молчаливое приятие было бы хуже пропущенной проверки: питон собрал бы
    приложение своим путём, а Kotlin -- договором, и разошлись бы они не здесь,
    а у пользователя.
    """
    from oneframework import App
    from conftest import план

    with pytest.raises(Exception, match="пакет объявления"):
        план(App(_Пусто, title="T"))


def test_хоть_один_пример_вправду_сеет():
    """Иначе сверка посева зеленела бы на пустых списках."""
    готово = subprocess.run([sys.executable, "-c", _СВЕРКА, str(ROOT), "todo"],
                            capture_output=True, text=True, encoding="utf-8", cwd=str(ROOT))
    assert готово.returncode == 0, готово.stderr
    посев = json.loads(готово.stdout)["посев_из_пакета"]
    assert посев and any(п["rows"] for п in посев), посев


def test_примеры_вообще_нашлись():
    assert len(ПРИМЕРЫ) >= 6
