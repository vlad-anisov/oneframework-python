"""Каждое написание языка выражений обязано быть прочитано выборкой.

Написание -- **строка**: выражение объявляется ею, одинаково на всех трёх
языках, а дерево из неё собирает сборка (`libs/js/src/build/exprtext.mjs`).
Здесь проверяется вся цепочка целиком -- строка, разбор, компилятор, -- а не
кусок её посередине.

Раньше эта проверка строила узлы питоновскими классами и спрашивала выборку про
них. Классов больше нет, и это к лучшему: они были **третьей** записью языка --
после договора и разборщика, -- и разрыв между «питон печатает» и «выборка
читает» ловился на дороге, которой никто не ходит. Ходят этой.

Разрыв, ради которого проверка стоит, тот же: узел, который в объявлении
написать можно, а выборка не читает, доезжает не отказом, а пустым списком на
экране. Заметить это можно только по чужой жалобе.
"""

import json
from pathlib import Path

import pytest

from jsrel import call, needs_node

pytestmark = needs_node

КОРЕНЬ = Path(__file__).resolve().parents[1]

#: Написание -> род узла договора, который оно обязано дать. Род называется
#: явно, а не выводится из ответа: иначе опечатка в написании тихо проверяла бы
#: не тот узел, и род остался бы без сторожа.
НАПИСАНИЯ = [
    ("record.done",                     "record_ref"),
    ("record.price > 100",              "cmp"),
    ('record.title = "Крыша"',          "cmp"),
    ("record.done & record.price > 1",  "and"),
    ("record.done | record.price > 1",  "or"),
    ("!record.done",                    "not"),
    ("record.title = null",             "is_null"),
    ("record.price + 1",                "arith"),
    ("record.price / 2",                "arith"),
    ("record.price % 2",                "arith"),
    ("record.price ** 2",               "arith"),
    ("-record.price",                   "arith"),
    ("abs(record.price)",               "arith"),
    ("if(record.done, 1, 0)",           "arith"),
    ("round(record.price)",             "arith"),
    ("length(record.title)",            "arith"),
    ("upper(record.title)",             "arith"),
    ('startswith(record.title, "Кры")', "arith"),
    ("text(record.price)",              "arith"),
    ("count(Task, record.done, via=board)",   "aggregate"),
    ("exists(Task, record.done, via=board)",  "aggregate"),
    ("sum(Task, record.price, via=board)",    "aggregate"),
    ("min(Task, record.price, via=board)",    "aggregate"),
    ("max(Task, record.price, via=board, on_empty=0)", "aggregate"),
]

#: Роды договора, которых нет среди написаний выше, и почему. Список, а не
#: пропуск в теле: исключение обязано быть названо, иначе следующий добавит
#: своё молча.
БЕЗ_НАПИСАНИЯ = {
    #: Узел «строкой» -- это и есть то, чем написано всё остальное. Написать
    #: его написанием нельзя: он был бы строкой внутри строки.
    "text",
    #: Шаблон и порядок строит привязка, а не разборщик: `f"{record.name}"` и
    #: `record.date.desc()` -- части объявления вида, а не выражения. Их
    #: сторожат `test_expand.py` и `test_dsl.py`.
    "template", "order",
    #: «Не выбрано» -- состояние экрана, а не написанное условие: его кладёт
    #: рантайм, когда фильтр не тронут.
    "unset",
    #: Точка через связь -- вывод компилятора, а не написание: `record.board.name`
    #: он разворачивает в подзапрос сам.
    "lookup",
    #: Ссылка вида и ссылка строки требуют обстановки -- состояния экрана и
    #: разворачиваемой записи, -- а `compile_expr` спрашивают без неё. Их
    #: сторожит `test_dsl.py`, где обстановка есть: «record.tag = view.tag»
    #: собирается там в настоящий SQL.
    "view_ref", "item_ref",
}


@pytest.mark.parametrize("написание,род", НАПИСАНИЯ, ids=[н for н, _ in НАПИСАНИЯ])
def test_каждое_написание_читается_выборкой(написание, род):
    """Написали -- значит обязаны прочитать."""
    # Хост разворачивает строку ровно так же, как это делает сборка: рантайм
    # строк не видит, и спрашивать выборку про строку значило бы проверять
    # дорогу, которой на устройстве нет.
    кусок = call("compile_expr", {"text": написание})
    assert кусок["sql"] and кусок["sql"] != "NULL", (
        f"{написание}: выборка ничего не собрала")


def test_написания_покрывают_весь_договор():
    """Роды из договора сверяются со списком выше, а не живут отдельно.

    Заведут шестнадцатый род -- этот тест назовёт его по имени, и он не проедет
    молча мимо выборки.
    """
    договор = json.loads((КОРЕНЬ / "protocol" / "expression.json").read_text(
        encoding="utf-8"))
    роды = set(договор["nodes"])
    покрыто = {род for _, род in НАПИСАНИЯ}
    забыто = роды - покрыто - БЕЗ_НАПИСАНИЯ
    assert not забыто, f"роды договора не проверены выборкой: {sorted(забыто)}"


def test_исключения_переживают_только_свои_роды():
    """Список исключений не должен пережить род, ради которого заведён."""
    договор = json.loads((КОРЕНЬ / "protocol" / "expression.json").read_text(
        encoding="utf-8"))
    лишние = sorted(БЕЗ_НАПИСАНИЯ - set(договор["nodes"]))
    assert not лишние, f"названы исключениями, а таких родов нет: {лишние}"
