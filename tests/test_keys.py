"""Ключ записи и отметка порядка -- то, что меняется до всякого обмена.

Отдельно от `test_sync.py` намеренно: обмен требует APSW, а **это** работает на
любом драйвере -- и именно так оно и работает на устройстве, где APSW пока нет.
Миграция установленной базы -- операция однократная и необратимая, и проверять
её только там, где её никогда не будет, значило бы не проверять вовсе.
"""

from __future__ import annotations

from oneframework import Boolean, Integer, Many2many, Many2one, Model, String


class Tag(Model):
    _label = "Метка"
    name = String("Метка")


class Board(Model):
    _label = "Список"
    name = String("Название", required=True)


class Task(Model):
    _label = "Задача"
    title = String("Задача", required=True)
    done = Boolean("Выполнено")
    sequence = Integer()
    board = Many2one(Board, "Список")
    tags = Many2many(Tag, "Метки")


MODELS = [Tag, Board, Task]




